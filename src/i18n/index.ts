export type TKey = keyof (typeof dict)['en']

export function translate(lang: Lang, key: TKey): string {
  const table = dict[lang] as Record<string, string>
  return table[key] ?? dict.en[key] ?? String(key)
}

export function phaseKey(phase: Phase): TKey {
  return phase === 'focus' ? 'phase_focus' : phase === 'short' ? 'phase_short' : 'phase_long'
}
export function phaseStatusKey(phase: Phase): TKey {
  return phase === 'focus'
    ? 'phase_focus_status'
    : phase === 'short'
      ? 'phase_short_status'
      : 'phase_long_status'
}
export function pageKey(page: PageId): TKey {
  return (`nav_${page}` as TKey)
}
export function categoryKey(c: Category): TKey {
  return (`cat_${c}` as TKey)
}
export function kindKey(kind: PresetKind): TKey {
  return (`mode_${kind}` as TKey)
}
export function kindDescKey(kind: PresetKind): TKey {
  return (`mode_${kind}_d` as TKey)
}
